async function seedFaculties(): Promise<void> {
  for (const name of faculties) {
    await prisma.faculty.upsert({ where: { name }, update: {}, create: { name } });
  }
}

async function seedInstitutions(): Promise<void> {
  for (const institution of institutions) {
    await prisma.institution.upsert({
      where: { name: institution.name },
      update: { abbreviation: institution.abbreviation, esUniversidad: institution.esUniversidad },
      create: institution,
    });
  }
}

async function seedDestinations(): Promise<void> {
  for (const description of destinations) {
    await prisma.destination.upsert({
      where: { description },
      update: {},
      create: { description },
    });
  }
}

async function seedResearchLines(): Promise<void> {
  for (const line of researchLines) {
    await prisma.researchLine.upsert({
      where: { name_type: { name: line.name, type: line.type } },
      update: {},
      create: line,
    });
  }
}

async function seedModalities(): Promise<void> {
  for (const modality of modalities) {
    await prisma.modality.upsert({
      where: { name: modality.name },
      update: { fee: modality.fee },
      create: modality,
    });
  }
}

async function main(): Promise<void> {
  await seedFaculties();
  await seedInstitutions();
  await seedDestinations();
  await seedResearchLines();
  await seedModalities();
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
